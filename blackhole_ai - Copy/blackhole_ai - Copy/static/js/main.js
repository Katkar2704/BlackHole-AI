let chatHistory = [];

async function sendMessage() {
    const input = document.getElementById('user-input');
    const btn = document.getElementById('send-btn');
    const loader = document.getElementById('blackhole-loader');
    const query = input.value.trim();
    
    if (!query) return;

    // UI state
    input.value = '';
    btn.disabled = true;
    loader.classList.remove('hidden');
    appendMessage('user', query);

    try {
        const response = await fetch('/api/chat', {
            method: 'POST',
            headers: {'Content-Type': 'application/json'},
            body: JSON.stringify({ 
                query, 
                llm: document.getElementById('llm-selector').value, 
                history: chatHistory 
            })
        });

        const data = await response.json();
        if (data.error) throw new Error(data.error);

        chatHistory.push({role:'user', content: query}, {role:'assistant', content: data.response});
        appendMessage('ai', data.response, data.metadata);
        
    } catch (e) { 
        appendMessage('ai', "SYSTEM ERROR: Could not connect to BlackHole Core. Verify Groq API Key."); 
    } finally { 
        btn.disabled = false;
        loader.classList.add('hidden');
    }
}

function appendMessage(sender, text, meta = null) {
    const container = document.getElementById('messages');
    const msgDiv = document.createElement('div');
    msgDiv.className = `flex flex-col ${sender === 'user' ? 'items-end' : 'items-start'} mb-8 animate-fade-in`;

    // 1. Render Markdown Content
    let bodyHtml = (sender === 'ai') ? marked.parse(text) : `<p>${text}</p>`;

    // 2. Build Sources List
    let sourcesHtml = '';
    if (meta && meta.sources && meta.sources.length > 0) {
        sourcesHtml = `
            <div class="mt-4 pt-3 border-t border-gray-800 flex flex-wrap gap-2">
                ${meta.sources.slice(0, 5).map(url => `
                    <a href="${url}" target="_blank" class="source-tag">
                        <i class="fas fa-link mr-1"></i> ${new URL(url).hostname.replace('www.', '')}
                    </a>
                `).join('')}
            </div>`;
    }

    // 3. Build Model Badge
    let badgeHtml = (meta && sender === 'ai') ? `
        <div class="mt-4 flex items-center justify-between w-full">
            <span class="text-[10px] font-bold text-blue-500 uppercase tracking-widest">
                🚀 GENERATED BY ${meta.llm}
            </span>
            <span class="text-[9px] text-gray-600 bg-gray-900 px-2 py-0.5 rounded border border-gray-800">
                ${meta.domain} | Complexity: ${meta.complexity}
            </span>
        </div>` : '';

    msgDiv.innerHTML = `
        <div class="max-w-[85%] p-5 rounded-2xl ${sender === 'user' ? 'bg-blue-600 text-white shadow-xl' : 'bg-[#0d0d0d] border border-gray-800 ai-bubble shadow-2xl'}">
            <div class="markdown-content text-[14px] leading-relaxed">${bodyHtml}</div>
            ${sourcesHtml}
            ${badgeHtml}
        </div>`;

    container.appendChild(msgDiv);

    // 4. Post-Process AI Code Blocks for Copy Button & Highlighting
    if (sender === 'ai') {
        const codeBlocks = msgDiv.querySelectorAll('pre');
        codeBlocks.forEach((pre) => {
            const codeEl = pre.querySelector('code');
            if (codeEl) {
                const language = codeEl.className.replace('language-', '') || 'code';
                const originalCode = codeEl.innerText;

                // Create the header
                const header = document.createElement('div');
                header.className = 'code-header';
                header.innerHTML = `
                    <span>${language.toUpperCase()}</span>
                    <button class="copy-btn"><i class="far fa-copy"></i> Copy code</button>
                `;

                // Add Copy Functionality
                header.querySelector('.copy-btn').onclick = function() {
                    navigator.clipboard.writeText(originalCode);
                    this.innerHTML = `<i class="fas fa-check text-green-500"></i> Copied!`;
                    setTimeout(() => { this.innerHTML = `<i class="far fa-copy"></i> Copy code`; }, 2000);
                };

                // Inject header before the code element
                pre.insertBefore(header, codeEl);
                hljs.highlightElement(codeEl);
            }
        });
    }

    container.scrollTo({ top: container.scrollHeight, behavior: 'smooth' });
}